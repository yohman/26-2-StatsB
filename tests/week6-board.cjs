const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const elements=new Map();
const element=id=>{if(!elements.has(id))elements.set(id,{value:id==='rows'?'12':id==='speed'?'1':id==='scale'?'0.4':'',textContent:'',innerHTML:'',disabled:false});return elements.get(id);};
const ctx=new Proxy({}, {get:(o,k)=>o[k]||(()=>{}),set:(o,k,v)=>(o[k]=v,true)});
let nextId=0,time=0;
const frames=new Map();
const canvas={getContext:()=>ctx};
const host={classList:{add(){}},set innerHTML(v){this.html=v;},querySelector:selector=>selector==='canvas'?canvas:element(selector.slice(1))};
const sandbox={window:{},Math,requestAnimationFrame:fn=>{frames.set(++nextId,fn);return nextId;},cancelAnimationFrame:id=>frames.delete(id)};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('assets/week6-math.js','utf8'),sandbox);
vm.runInContext(fs.readFileSync('assets/week6-board.js','utf8'),sandbox);
sandbox.window.StatsBWeek6Board(host);
function tick(count){for(let i=0;i<count;i++){time+=16;const current=[...frames.values()];frames.clear();current.forEach(fn=>fn(time));}}
const theoreticalBars=()=>element('hist').innerHTML.match(/<rect[^>]+fill="#e4f0f1"[^>]*>/g);
const expected=theoreticalBars();
element('many').onclick();
tick(120);
assert.match(element('flight').textContent,/移動中/);
assert.equal(element('landed').textContent,0);
element('pause').onclick();
const paused=element('flight').textContent;
tick(200);
assert.equal(element('flight').textContent,paused);
element('pause').onclick();
tick(1200);
assert.equal(element('landed').textContent,100);
const counts=[...element('hist').innerHTML.matchAll(/aria-label="右へ\d+回。(\d+)個。/g)].map(m=>+m[1]);
assert.equal(counts.reduce((a,b)=>a+b,0),100);
assert.deepEqual(theoreticalBars(),expected,'Theory must remain fixed as observations arrive');
assert.equal(element('one').disabled,false);
assert.equal(element('pause').disabled,true);
element('one').onclick();tick(300);
assert.equal(element('landed').textContent,101);
element('many').onclick();tick(30);element('reset').onclick();tick(1000);
assert.equal(element('landed').textContent,0,'Reset must cancel in-flight arrivals');
element('rows').value='20';element('rows').onchange();element('one').onclick();tick(400);
assert.equal(element('landed').textContent,1);
assert.match(element('status').textContent,/20段/);
console.log('Galton board: visible flight phase, pause/resume, exact arrival counts, fixed theory, reset cancellation, and 20-row completion.');
